// Turns public/icons/**/*.svg into src/components/icons/iconData.generated.ts so icons are drawn inline (no request per icon,
// no pop-in when a menu opens). Run `npm run icons` after adding or changing an SVG there.
//  - ids and clip-paths are dropped so many copies of one icon on a page never clash
//  - icons under nav/ take the current text colour (they were tinted that way before)
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";

const root = new URL("../public/icons/", import.meta.url).pathname;
const out = new URL("../src/components/icons/iconData.generated.ts", import.meta.url).pathname;

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : p.endsWith(".svg") ? [p] : [];
  });
}

const icons = {};
for (const file of walk(root).sort()) {
  const name = relative(root, file).split(sep).join("/").replace(/\.svg$/, "");
  const svg = readFileSync(file, "utf8");
  if (/<(linearGradient|radialGradient|filter|mask|pattern|image|style)\b/.test(svg)) throw new Error(`${name}: uses features the inliner does not handle`);
  const root_ = svg.match(/<svg\b([^>]*)>/);
  const attr = (n) => root_[1].match(new RegExp(`\\s${n}="([^"]*)"`))?.[1];
  let body = svg.slice(root_.index + root_[0].length, svg.lastIndexOf("</svg>"));
  body = body.replace(/<defs>[\s\S]*?<\/defs>/g, "").replace(/\sclip-path="[^"]*"/g, "").replace(/\sid="[^"]*"/g, "").replace(/\s+/g, " ").replace(/> </g, "><").trim();
  if (name.startsWith("nav/")) body = body.replace(/\s(fill|stroke)="(?!none)[^"]*"/g, ' $1="currentColor"');
  const vb = (attr("viewBox") || "").split(/\s+/).map(Number);
  icons[name] = { w: parseFloat(attr("width")) || vb[2], h: parseFloat(attr("height")) || vb[3], viewBox: attr("viewBox"), body };
}

writeFileSync(out, `// GENERATED by scripts/build-icons.mjs from public/icons. Do not edit by hand.\nexport const ICONS: Record<string, { w: number; h: number; viewBox: string; body: string }> = ${JSON.stringify(icons, null, 1)};\n`);
console.log(`wrote ${Object.keys(icons).length} icons -> src/components/icons/iconData.generated.ts`);
